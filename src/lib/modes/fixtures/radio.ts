type RadioFixtureRecord = {
  detail: TerraPointDetail;
  point: TerraPoint;
  streamUrl: string;
};

const FIXTURE_TIMESTAMP = "2026-01-01T00:00:00.000Z";

function createFixtureRecord(
  id: string,
  name: string,
  latitude: number,
  longitude: number,
  country: string,
  countryCode: string,
  language: string,
  codec: string,
  bitrate: string,
  tags: string,
  streamUrl: string,
  sourceUrl: string
): RadioFixtureRecord {
  const point: TerraPoint = {
    id,
    modeId: "radio",
    name,
    latitude,
    longitude,
    countryCode,
    prominence: 0.45,
    timestamp: FIXTURE_TIMESTAMP,
    summary: `${country} · ${language} · ${tags}`,
    metrics: {
      Bitrate: bitrate,
      Clicks: 0,
      Codec: codec,
      Country: country,
      Language: language,
      Tags: tags,
      Votes: 0
    }
  };

  return {
    point,
    detail: {
      ...point,
      fields: [
        { label: "Country", value: country },
        { label: "Language", value: language },
        { label: "Codec", value: codec },
        { label: "Bitrate", value: bitrate },
        { label: "Votes", value: "0" },
        { label: "Tags", value: tags }
      ],
      sourceUrl
    },
    streamUrl
  };
}

